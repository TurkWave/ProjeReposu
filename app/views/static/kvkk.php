<article class="kvkk-content">
    <h2>KVKK Aydınlatma Metni</h2>
    <p><strong>1. Açıklık</strong><br>
    Staj Takip uygulaması, staj sürecinizi yönetmek amacıyla kişisel verilerinizi
    <strong>minimum düzeyde</strong> toplar.</p>

    <p><strong>2. Toplanan Veriler</strong><br>
    - Adınız, soyadınız, e-posta adresiniz (hesap ve iletişim için)<br>
    - Staj yoklaması (tarih, var/yok, isteğe bağlı konum)<br>
    - Staj defteri notları ve isteğe bağlı fotoğraf<br>
    - Sorun bildirimleriniz (anonim seçeneği mevcuttur)<br>
    - 18 yaş altıysanız, veli onayı bilgisi</p>

    <p><strong>3. Kullanım Amaçları</strong><br>
    Verileriniz yalnızca staj takibini, yoklamayı, defter kaydını ve sorun
    bildirimlerinizi yönetmek için kullanılır. Üçüncü şahıslarla paylaşılmaz.</p>

    <p><strong>4. Haklarınız</strong><br>
    Kişisel verilerinize ilişkin: düzeltme, silme, erişim ve itiraz haklarını
    kullanabilirsiniz. Detaylı bilgi için okulun KVKK görevlisine başvurun.</p>

    <p><strong>5. Saklama Süresi</strong><br>
    Staj süresince ve ardından 1 yıl saklanır.</p>

    <p><strong>6. Çocukların Verileri</strong><br>
    18 yaş altı kullanıcılar için veli onayı zorunludur; bu onayı sizden
    ayrı olarak velinizden alırız.</p>

    <p><strong>7. Güvenlik</strong><br>
    Şifrelenmiş oturum, hazırlıklı ifadeler (prepared statements) ve satır
    (rol) bazlı erişimle verileriniz güvende saklanır.</p>

    <p><strong>8. İletişim</strong><br>
    Veri sorumlunuz: <em>Okul Staj Koordinatörü</em>. Sorularınız için
    sistemdeki öğretmen hesabınıza mesaj yazabilirsiniz.</p>
</article>
